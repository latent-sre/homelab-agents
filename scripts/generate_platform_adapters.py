def _safe_generated_root(root: Path, relative: Path, *, operation: str) -> Path:
    if relative not in (*GENERATED_ROOTS, *RETIRED_GENERATED_ROOTS):
        raise ValueError(f"refusing to {operation} undeclared generated path: {relative}")

    resolved_root = root.resolve()
    target = resolved_root / relative
    if target == resolved_root or not target.is_relative_to(resolved_root):
        raise ValueError(
            f"refusing to {operation} generated path outside repository: {target}"
        )

    current = resolved_root
    for part in relative.parts:
        current /= part
        _assert_no_generated_path_indirection(current, operation=operation)
    return target


def _replace_generated_file(path: Path, content: bytes) -> None:
    """Replace a standalone generated file by directory entry, never by truncating its inode.

    `write_bytes` opens the EXISTING inode and truncates it. A hard link is indistinguishable from
    a regular file -- `lstat` reports one, and the link/reparse checks above cannot see it -- so a
    hard link at `hooks/hooks.json` pointing at a file outside the checkout means `--write`
    silently overwrites that file and leaves the link in place. Reproduced on this PR's own head
    (Codex, PR #193). Writing a sibling temp file and `os.replace`-ing it swaps the directory
    entry instead: the old inode keeps its bytes, the outside file is untouched, and the swap is
    atomic, so a concurrent reader never sees a half-written or absent hook.

    The files inside a generated ROOT do not need this: `--write` removes and recreates those
    directories, so every entry there is a fresh inode before it is written.
    """

    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent, prefix=f".{path.name}.", suffix=".tmp"
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(content)
        os.replace(temporary, path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def _safe_generated_file(root: Path, relative: Path, *, operation: str) -> Path:
    """Resolve a declared standalone generated file, refusing any link-like path COMPONENT.

    `_safe_generated_root`'s sibling, and it walks the ancestors for the same reason: checking
    only the leaf leaves `hooks/` free to be a link, and both validation and `--write` would then
    read and overwrite a file outside the checkout while the repository looked regenerated
    (Copilot, PR #193 -- the leaf-only version shipped in this PR's first push).
    """

    if relative not in GENERATED_FILES:
        raise ValueError(f"refusing to {operation} undeclared generated path: {relative}")

    resolved_root = root.resolve()
    target = resolved_root / relative
    if target == resolved_root or not target.is_relative_to(resolved_root):
        raise ValueError(
            f"refusing to {operation} generated path outside repository: {target}"
        )

    current = resolved_root
    for part in relative.parts:
        current /= part
        _assert_no_generated_path_indirection(current, operation=operation)
    return target


def _remove_generated_root(target: Path) -> None:
    """Clear a generated or retired root, whatever shape it is on disk.

    A declared root that is a regular file is still an obsolete artifact and still has to go;
    `shutil.rmtree` refuses one, which aborted the whole write on a path the preview had already
    promised to remove. The link guard runs before this, so nothing here follows a link.
    """

    if not target.exists():
        return
    if target.is_dir():
        shutil.rmtree(target)
    else:
        target.unlink()


