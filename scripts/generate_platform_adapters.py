#!/usr/bin/env python3
"""Generate Codex and Copilot/VS Code adapters from the Claude-canonical fleet.

The authored source remains ``agents/*.md`` and ``skills/**``. Other hosts do not share Claude's
agent frontmatter, plugin namespace, hook payload, or skill invocation syntax, so loading those
files unchanged creates plausible-looking but false controls. This generator makes those
differences explicit:

* Copilot/VS Code agents use native tool aliases. Agents protected by Claude's session-wide Bash
  hook receive no ``execute`` tool because neither host exposes the active agent identity on
  ``PreToolUse``.
* Codex agents use standalone TOML and request ``read-only`` or ``workspace-write`` sandbox mode
  from the canonical write-tool authority, while naming that parent permissions can override it.
* Each host gets a skill copy with valid YAML, no Claude plugin namespace, and no direct
  plugin-root paths. Copilot retains its explicit-invocation frontmatter; Codex expresses the
  same rule through ``agents/openai.yaml``.

Every prose projection is declared in ``fleet/hosts/table.py`` with the number of times it must
land across one generation run, and ``expected_outputs`` refuses to hand back bytes whose rewrites
did not land those counts. That closes the class this generator used to carry one anchor at a
time: a canonical sentence is reworded, the rewrite that corrected it silently stops matching, and
the regenerated adapter keeps a Claude-only authority claim that byte-drift validation cannot see,
because the committed copy was produced with the same miss (PR #141 finding).

Generated directories are replaced as a unit by ``--write``, previewed by ``--diff``, and checked
byte-for-byte by the fleet validator. Never edit generated output directly.
"""

